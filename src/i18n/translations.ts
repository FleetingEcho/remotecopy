export function t(
  lang: Lang,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const table = lang === "zh" ? zh : en;
  let msg = table[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      msg = msg.replace(`{${k}}`, String(v));
    }
  }
  return msg;
}
